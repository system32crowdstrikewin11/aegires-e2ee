// Generates src/selftest-vectors.ts and src/forced.ts with test/reference2.mjs (node:crypto only).
//   node test/gen-selftest-vectors.mjs
import fs from "node:fs";
import * as ref from "./reference2.mjs";

const CH = "1562876012675465326", SENDER = "123456789012345678";
const key = Buffer.from(Array.from({ length: 32 }, (_, i) => (i * 7 + 3) & 255));
const hex = (b) => Buffer.from(b).toString("hex");

const msgs = [
  { label: "AES-128 ascii", preset: 0, plain: "hello from AES-128" },
  { label: "AES-192 unicode", preset: 1, plain: "unicode ☃ 🔒 éè 日本語 — AES-192" },
  { label: "AES-256 long", preset: 2, plain: "The quick brown fox jumps over the lazy dog. ".repeat(8) },
].map((m) => ({ ...m, wire: ref.encMsg(m.plain, key, ref.PRESETS[m.preset], CH, SENDER) }));

const filePlain = Buffer.from(Array.from({ length: 100 }, (_, i) => (i * 13 + 5) & 255));
const fileWire = ref.encFile(filePlain, key, ref.PRESETS[1], CH, SENDER);

const kdf = [
  { label: "user key (m=1024)", password: "pässwörd-☃", context: null, memoryKiB: 1024, key: hex(ref.master("pässwörd-☃", "dcenc2|user-key|v1", 1024)) },
  { label: "context key (m=1024)", password: "mojoen", context: "forced|" + CH, memoryKiB: 1024, key: hex(ref.master("mojoen", "dcenc2|ctx|forced|" + CH, 1024)) },
];

let out = "// GENERATED by test/gen-selftest-vectors.mjs (reference: node:crypto only). Do not edit.\n";
out += "// Used by the on-device self-test: proves AES-128/192/256, short GCM tags, HKDF, file chunks and Argon2id\n// all give the right bytes on THIS phone's JS engine.\n";
out += `export const MASTER_HEX = ${JSON.stringify(hex(key))};\nexport const CHANNEL_ID = ${JSON.stringify(CH)};\nexport const SENDER_ID = ${JSON.stringify(SENDER)};\n`;
out += `export const MESSAGES: Array<{ label: string; preset: number; plain: string; wire: string }> = ${JSON.stringify(msgs, null, 2)};\n`;
out += `export const FILE = { label: "AES-192 file, 100 bytes", plainHex: ${JSON.stringify(hex(filePlain))}, wireHex: ${JSON.stringify(hex(fileWire))} };\n`;
out += `export const KDF: Array<{ label: string; password: string; context: string | null; memoryKiB: number; key: string }> = ${JSON.stringify(kdf, null, 2)};\n`;
fs.writeFileSync(new URL("../src/selftest-vectors.ts", import.meta.url), out);

const forcedKey = hex(ref.master("mojoen", "dcenc2|ctx|forced|" + CH));
const forced = `// Channels that always use a built-in password (Aegires ForcedKeys.java). This is an INTENDED Aegires
// feature: the channel is public, so nobody has to type a key - everyone gets it automatically.
// Messages there are always encrypted, always AES-128-GCM (like Aegires), and the key is
//   Argon2id(password, salt "dcenc2|ctx|forced|<channelId>")   - stored here already derived,
// so the phone does not need to run the slow Argon2id step for it.
export const FORCED_CHANNELS: Record<string, { keyHex: string }> = {
  ${JSON.stringify(CH)}: { keyHex: ${JSON.stringify(forcedKey)} },
};
`;
fs.writeFileSync(new URL("../src/forced.ts", import.meta.url), forced);
console.log("wrote src/selftest-vectors.ts and src/forced.ts; forced key", forcedKey);
